"""Build the living-room level: levels/living_room.xml (+ floor/rug textures in levels/textures/).

Real-world scale, so the hexapod is a toy on the floor: sofa, coffee table (you can walk
under it), TV unit, bookcase, armchair, plant, a rug, a fireplace hearth you climb onto via a
stack of books (racecourse finish), and loose props to push or shoot: cans, paper cups,
a toy-block tower and a ball.

    python tools/make_living_room.py

Copy this file to make your own room: change the numbers, move things, add props.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402

from quadsim.levelkit import Level  # noqa: E402

TEX = ROOT / "levels" / "textures"


def save_png(arr: np.ndarray, path: pathlib.Path):
    """uint8 HxWx3 -> PNG (pygame is already a dependency)."""
    import os
    os.environ.setdefault("PYGAME_HIDE_SUPPORT_PROMPT", "1")
    import pygame
    path.parent.mkdir(parents=True, exist_ok=True)
    pygame.image.save(pygame.surfarray.make_surface(arr.transpose(1, 0, 2)), str(path))


def make_textures():
    rng = np.random.default_rng(7)
    # wooden floorboards: 6 planks across the tile, staggered ends, grain streaks
    H = W = 512
    img = np.zeros((H, W, 3))
    plank_w = H // 6
    for p in range(6):
        base = np.array([0.55, 0.36, 0.2]) * rng.uniform(0.82, 1.12)
        y0 = p * plank_w
        x = np.arange(W)
        grain = 0.06 * np.sin(x[None, :] / rng.uniform(6, 14) + rng.uniform(0, 6)) \
            + 0.05 * rng.standard_normal((plank_w, W)).cumsum(axis=1) / np.sqrt(np.arange(1, W + 1))
        img[y0:y0 + plank_w] = base * (1 + grain[..., None])
        img[y0:y0 + 2] *= 0.55                                  # gap between planks
        cut = int(rng.uniform(0.2, 0.8) * W)
        img[y0:y0 + plank_w, cut:cut + 2] *= 0.6                 # board end
    save_png(np.clip(img * 255, 0, 255).astype(np.uint8), TEX / "wood_floor.png")

    # rug: border + diamond pattern
    H = W = 256
    yy, xx = np.mgrid[0:H, 0:W] / H
    rug = np.ones((H, W, 3)) * np.array([0.55, 0.12, 0.12])
    border = (np.minimum(np.minimum(xx, 1 - xx), np.minimum(yy, 1 - yy)) < 0.08)
    rug[border] = [0.85, 0.75, 0.55]
    diamond = (np.abs((xx * 6) % 1 - 0.5) + np.abs((yy * 6) % 1 - 0.5)) < 0.22
    rug[diamond & ~border] = [0.2, 0.25, 0.45]
    rug *= 1 + 0.06 * rng.standard_normal((H, W, 1))
    save_png(np.clip(rug * 255, 0, 255).astype(np.uint8), TEX / "rug.png")


def build():
    make_textures()
    lv = Level("Living room", "Living room at real scale (5 x 4 m). Generated by tools/make_living_room.py - "
                              "edit that script, not this file.")
    lv.texture("wood_floor", file="textures/wood_floor.png")
    lv.texture("rug", file="textures/rug.png")
    lv.material("wood_floor", texture="wood_floor", repeat=(1.2, 1.2), rgba=(1, 1, 1, 1))
    lv.material("rug", texture="rug", rgba=(1, 1, 1, 1))
    lv.material("wood", rgba=(0.62, 0.45, 0.3, 1))
    lv.material("wood_dark", rgba=(0.32, 0.22, 0.15, 1))
    lv.material("fabric", rgba=(0.42, 0.44, 0.48, 1))
    lv.material("wall", rgba=(0.86, 0.84, 0.79, 1))
    lv.material("brick", rgba=(0.55, 0.3, 0.24, 1))

    # Floating house: no endless ground, sky or sun - the room sits on a slab in a dark void, which is
    # less to draw. x in [-2.5, 2.5], y in [-2, 2]; the door in the south wall opens onto a small porch
    # that ends in a drop (fall off and you'll need to reset).
    H = 2.4                                                   # ceiling height
    lv.floating()
    lv.floor("wood_floor", area=(-2.6, 2.6, -2.1, 2.1))
    lv.box((1.4, 1.0, 0.12), (0.0, -2.6, -0.12), (0.5, 0.48, 0.45), name="porch")   # porch slab outside the door
    lv.walls(-2.5, 2.5, -2.0, 2.0, height=H, look="wall", door=("south", 0.0, 0.9))
    lv.box((1.1, 0.12, H - 2.05), (0.0, -2.05, 2.05), "wall", name="lintel")          # wall above the door
    lv.ceiling(-2.6, 2.6, -2.1, 2.1, H, look=(0.93, 0.93, 0.9))
    lv.ceiling_light(-0.7, 0.2, H, shadows=True, brightness=0.6)   # over the coffee table (casts shadows)
    lv.ceiling_light(1.5, -0.6, H, brightness=0.35)
    lv.ceiling_light(1.2, 1.3, H, brightness=0.3)
    lv.window(-2.49, 0.9, 1.0, 1.0, 1.0, yaw=90)                    # windows (glowing panes) on the west...
    lv.window(1.0, -1.99, 1.0, 1.2, 1.0)                            # ...and south walls

    # rug (6 mm thick - you'll feel the step) + coffee table on it (42 cm high: walk underneath)
    lv.box((1.6, 2.2, 0.006), (-0.7, 0.2, 0), "rug", name="rug", friction=1.4)
    lv.table(-0.7, 0.2, 1.1, 0.6, 0.42, yaw=90)
    # sofa against the west wall, facing the TV
    lv.sofa(-2.0, 0.2, length=2.1, yaw=0)
    # TV unit + TV on the east wall
    lv.box((0.4, 1.6, 0.45), (2.25, 0.2, 0), "wood_dark", name="tv_unit")
    lv.box((0.06, 1.1, 0.62), (2.3, 0.2, 0.45), (0.05, 0.05, 0.06), name="tv")
    lv.box((0.2, 0.3, 0.02), (2.3, 0.2, 0.45), (0.1, 0.1, 0.1))
    # armchair in the south-east corner, angled at the TV
    lv.sofa(1.7, -1.35, length=0.9, depth=0.8, yaw=135)
    # bookcase on the north wall, plant in the south-west corner
    lv.shelf(-0.6, 1.83, 1.2, 0.3, 1.5, shelves=4, look="wood", yaw=0)
    lv.plant(-2.2, -1.7)
    lv.plant(2.2, 1.7, pot_r=0.13, pot_h=0.25)

    # fireplace on the north wall: brick surround + 7 cm hearth, climbed via two books
    lv.box((1.3, 0.25, 0.9), (1.2, 1.88, 0), "brick")
    lv.box((0.7, 0.05, 0.5), (1.2, 1.76, 0.07), (0.08, 0.06, 0.05), collide=False)   # firebox opening
    lv.box((1.6, 0.6, 0.07), (1.2, 1.5, 0), (0.45, 0.43, 0.42), name="hearth")
    lv.box((0.42, 0.3, 0.035), (1.2, 1.05, 0), (0.15, 0.3, 0.55), name="book1")       # step 1
    lv.box((0.38, 0.26, 0.035), (1.2, 1.07, 0.035), (0.6, 0.15, 0.1), name="book2")   # step 2

    # loose props: push them, or shoot them
    for k, (dx, dy) in enumerate(((-0.15, 0.1), (0.05, -0.12), (0.18, 0.2))):         # cans on the table
        lv.free_cyl(0.033, 0.115, (-0.7 + dx, 0.2 + dy, 0.42), 0.015,
                    [(0.8, 0.1, 0.1), (0.1, 0.5, 0.2), (0.85, 0.8, 0.8)][k], name="can")
    for k in range(3):                                                                 # paper cups on the TV unit
        lv.free_cyl(0.035, 0.09, (2.2, -0.35 + 0.1 * k, 0.45), 0.005, (0.95, 0.95, 0.92), name="cup")
    s = 0.06                                                                           # toy-block tower on the rug
    blocks = [(0, 0, 0), (1, 0, 0), (2, 0, 0), (0.5, 0, 1), (1.5, 0, 1), (1, 0, 2)]
    cols = [(0.9, 0.2, 0.2), (0.2, 0.4, 0.9), (0.95, 0.8, 0.1), (0.2, 0.7, 0.3), (0.9, 0.5, 0.1), (0.6, 0.2, 0.7)]
    for (bx, by, bz), col in zip(blocks, cols):
        lv.free_box((s, s, s), (0.1 + bx * (s + 0.002), -0.6 + by, bz * s), 0.03, col, name="block")
    lv.free_sphere(0.1, (0.8, -0.2, 0), 0.06, (0.9, 0.25, 0.2), name="ball")          # light play ball

    lv.spawn(0.0, -1.55, yaw=90)                       # just inside the door, facing into the room
    lv.finish((1.2, 1.5, 0.07), (1.0, 0.45, 0.35))     # racecourse goal: up on the hearth
    lv.write(ROOT / "levels" / "living_room.xml")


if __name__ == "__main__":
    build()
