"""Regenerate levels/stairs.xml with different step sizes.

    python tools/make_stairs.py --rise 25 --run 140 --steps 5
"""
import argparse, pathlib

ap = argparse.ArgumentParser()
ap.add_argument("--rise", type=float, default=25, help="step height, mm")
ap.add_argument("--run", type=float, default=140, help="step depth, mm")
ap.add_argument("--steps", type=int, default=5)
ap.add_argument("--width", type=float, default=900, help="stair width, mm")
ap.add_argument("--start", type=float, default=600, help="distance from spawn to first step, mm")
ap.add_argument("--out", default=str(pathlib.Path(__file__).resolve().parent.parent / "levels" / "stairs.xml"))
a = ap.parse_args()
rise, run, width, n, x0 = a.rise / 1000, a.run / 1000, a.width / 1000, a.steps, a.start / 1000

geoms = []
for i in range(n):
    h = rise * (i + 1)
    cx = x0 + run * i + run / 2
    geoms.append(f'    <geom name="step{i+1}" type="box" size="{run/2:.3f} {width/2:.3f} {h/2:.4f}" pos="{cx:.3f} 0 {h/2:.4f}" material="stairs"/>')
plat_h, plat_len = rise * (n + 1), 1.0
px = x0 + run * n + plat_len / 2
geoms.append(f'    <geom name="platform" type="box" size="{plat_len/2:.3f} {width/2+0.3:.3f} {plat_h/2:.4f}" pos="{px:.3f} 0 {plat_h/2:.4f}" material="platform"/>')
finish = f'    <site name="finish" type="box" size="0.2 {width/2:.3f} 0.15" pos="{px+0.2:.3f} 0 {plat_h+0.15:.4f}" rgba="0.2 0.9 0.3 0.25"/>'
pathlib.Path(a.out).write_text(f'''<!-- Flat ground, then {n} steps ({rise*1000:.0f} mm rise, {run*1000:.0f} mm run) up to a raised platform
     ({plat_h*1000:.0f} mm). Racecourse mode: reach the green finish box on the platform.
     Generated by tools/make_stairs.py -->
<mujoco model="Stairs to platform">
  <worldbody>
    <geom name="floor" type="plane" size="0 0 0.05" material="grid"/>
{chr(10).join(geoms)}
{finish}
    <site name="spawn" pos="0 0 0" size="0.01" rgba="0 0 0 0"/>
  </worldbody>
</mujoco>
''')
print("wrote", a.out)
